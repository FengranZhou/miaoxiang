// ============================================================================
// liaison 工具自身的视觉令牌（Design Tokens）
// ----------------------------------------------------------------------------
// ## 这个文件解决什么
//
// 扩展的界面（工具条、各面板、组件浮层）此前**没有视觉规范**：颜色、圆角、
// 字号全是各处随手写的裸值。一次扫描的结果是「圆角 7 种、rgba 颜色 40 种」，
// 其中 4/5/7/9px 这些圆角在工具其余部分根本不存在（那边是 6/8/10/12/999）——
// 于是同一个工具里的两块界面长得不像一家的。
//
// ## 与 xiaoya 设计规范的关系
//
// **两者不是同一套，不要混用。** xiaoya 那套是给「教学业务页面」用的：
// 亮色、品牌绿、Element Plus 组件。这套是给「贴在别人网页上的批注工具」
// 用的：深色（不与宿主页面抢注意）、蓝色强调、纯手写 DOM。
//
// 借鉴的是**方法**（语义分层、整档取用、单一数据源），不是值。
//
// ## 怎么用
//
//   import 不了（内容脚本非模块），所以挂在 window.__liaisonUITokens 上。
//   写样式时用 T.color.bg1 这类语义名，**不要再写裸值**。
// ============================================================================

;(function () {
  if (typeof window === 'undefined' || window.__liaisonUITokens) return
  // ══════════════════════════════════════════════════════════════════════════
  // ① 颜色
  // ══════════════════════════════════════════════════════════════════════════
  //
  // 底色只有一个：#0F1B26（工具条与各面板已在用）。其余层次全部由
  // 白色叠加不同透明度得到 —— 好处是贴在任何宿主页面上都不会因为
  // 底色不同而露出色差，坏处是要克制透明度档位，否则又长出 40 种。
  const color = {
    // 面：深色底 + 分层
    'surface':        '#0F1B26',              // 面板底
    'surface-raised': 'rgba(255,255,255,.06)', // 抬起一层（列表项 hover、内嵌块）
    'surface-sunken': 'rgba(0,0,0,.24)',       // 凹陷一层（代码块、预览区）

    // 描边：三档，够了
    'line':        'rgba(255,255,255,.12)',  // 常规分隔 / 面板边框
    'line-subtle': 'rgba(255,255,255,.07)',  // 弱分隔（组内）
    'line-strong': 'rgba(255,255,255,.22)',  // 强调边框（聚焦、选中）

    // 文字：四阶，与 xiaoya 的四阶同构（正文/次要/占位/禁用）
    'text':         'rgba(255,255,255,.92)',
    'text-sub':     'rgba(255,255,255,.62)',
    'text-weak':    'rgba(255,255,255,.42)',
    'text-disabled':'rgba(255,255,255,.28)',

    // 主色：薄荷绿。这不是设计选择，是把工具现状写下来 —— 主按钮
    // （.effect-button、.lau-btn-primary）一直是 #65ffb6，这里跟它对齐。
    //
    // ⚠️ 薄荷绿很亮（相对亮度 .78），实心底上**必须配深字** primary-ink：
    //    深字 14.4:1 达标，白字只有 1.27:1，等于看不见。
    //    凡是 `background:var(--lz-c-primary)` 的地方，都要同时给 color。
    'primary':       '#65FFB6',
    'primary-hover': '#7AFFC4',
    'primary-weak':  'rgba(101,255,182,.16)', // 选中底 / 弱强调（白字压在上面 11.5:1）
    'primary-ink':   '#12151A',               // 压在 primary 实心底上的字/图标/滑块

    // 标记色：蓝。语义是「用户在页面上圈出来的东西」—— 批注圆点、区域框、
    // 拖拽选框、缩放手柄。与 primary 分开：那是「可以点的操作」，这是「被标注的位置」。
    //
    // 取值比原先的 #0077FF 深一档：pin 上的 11px 白字在 #0077FF 上只有 4.13:1，
    // 不达标；#0069E0 上是 5.13:1。作描边时在白底宿主页上 4.57:1，也比原先更清楚。
    'marker':       '#0069E0',
    'marker-weak':  'rgba(0,105,224,.12)',    // 框内填充（要能看见底下的宿主内容）

    // 语义
    'danger':      '#FF6B6B',
    'danger-weak': 'rgba(255,90,90,.14)',
    // ⚠️ 这里故意没有 success 绿：primary 已经是绿的，再来一档
    //    （原先的 #2BD67F 与薄荷绿互比只有 1.50:1）根本分不出来。
    //    需要表达「成功」时直接用 primary。
    'warning':     '#FFB84D',                 // 目前无消费者，保留：琥珀是 danger/primary 都替代不了的一档
  }

  // ══════════════════════════════════════════════════════════════════════════
  // ② 圆角 —— 与工具其余部分对齐（那边在用 6/8/10/12/999）
  // ══════════════════════════════════════════════════════════════════════════
  //
  // ⚠️ 4/5/7/9px  一律不要用：它们只出现在组件浮层里，是随手写的，
  // 与工具其余部分不成体系。旧值 → 新档的映射：4/5→sm(6)，7→md(8)，9/10→lg(10)。
  const radius = {
    sm: '6px',     // 小控件：按钮、输入框、列表项、标签
    md: '8px',     // 中等块：内嵌卡片、代码块、下拉项
    lg: '10px',    // 容器：面板、浮层、弹层
    xl: '12px',    // 大容器：整块卡片
    pill: '999px', // 胶囊：徽标、状态点、跟随提示
  }

  // ══════════════════════════════════════════════════════════════════════════
  // ③ 间距 —— 4 的倍数，只留 6 档
  // ══════════════════════════════════════════════════════════════════════════
  //
  // 扫出来的裸值有 2/3/5/7/9/11px 这类奇数，全是"看着差一点就调一格"的产物。
  // 归到 4 的倍数上：视觉节奏立刻统一，且以后不用再纠结「6 还是 7」。
  // 例外只留一个 2px（xxs），给图标与文字之间那种极紧的贴合。
  const space = {
    xxs: '2px',
    xs: '4px',
    sm: '8px',
    md: '12px',
    lg: '16px',
    xl: '24px',
  }

  // ══════════════════════════════════════════════════════════════════════════
  // ④ 字阶 —— 整档取用，禁止拆开自拼
  // ══════════════════════════════════════════════════════════════════════════
  //
  // 每档是 `font` 简写（字号/行高 + 字重一起给），照 xiaoya 那边「多档位体系
  // 必须整档取用」的纪律：不要单独改 font-size 去凑一档新的。
  //
  // ⚠️ 字体族含空格，`font` 简写里必须带引号，否则整条声明失效。
  const FAM = '-apple-system,BlinkMacSystemFont,"PingFang SC",sans-serif'
  const font = {
    // 正文两档：12 是主力（工具里 44 处在用），11 给密集信息
    body: '400 12px/1.5 ' + FAM,
    bodyStrong: '500 12px/1.5 ' + FAM,
    small: '400 11px/1.45 ' + FAM,
    smallStrong: '500 11px/1.45 ' + FAM,
    // 标题两档
    title: '600 13px/1.4 ' + FAM,
    titleLg: '600 14px/1.4 ' + FAM,
    // 等宽：代码 / 路径 / 尺寸数字
    mono: '400 10px/1.5 ui-monospace,SFMono-Regular,Menlo,monospace',
  }

  // ══════════════════════════════════════════════════════════════════════════
  // ⑤ 阴影 / 层级 / 动效
  // ══════════════════════════════════════════════════════════════════════════
  const shadow = {
    // 贴在宿主页面上，阴影要够重才压得住花花绿绿的背景 ——
    // 这与 xiaoya 那边「轻阴影」的取向刻意不同，不是抄漏了。
    sm: '0 2px 8px rgba(0,0,0,.28)',
    md: '0 10px 24px rgba(0,0,0,.34)',
    lg: '0 10px 34px rgba(0,0,0,.46)',
  }

  // z-index：工具必须盖在宿主页面之上，所以全部贴着 int32 上限排。
  // 档位之间留 1，够用且能一眼看出谁压谁。
  const z = {
    pick: 2147483644,   // 拾取高亮层 / 区域框（最底，会被标记盖住）
    mark: 2147483645,   // 页面标记（编号圆点、组件名标签）
    panel: 2147483646,  // 面板 / 浮层 / 跟随提示
    top: 2147483647,    // 下拉、确认弹层（必须盖住面板自己）
  }

  const motion = {
    fast: '.12s ease',      // 状态色变化（hover、按下）
    base: '.18s ease',      // 常规过渡（展开、位移）
    slow: '.32s cubic-bezier(.4,0,.2,1)', // 入场 / 退场
  }

  /**
   * 把令牌铺成 CSS 自定义属性，注入 documentElement。
   *
   * 为什么用 CSS 变量而不是让各处 JS 读对象拼字符串：变量能在 devtools 里
   * 直接改着看，也能被任何一段 CSS 引用 —— 包括写在模板字符串里的样式。
   * 变量名统一 `--lz-` 前缀（liaison），不会撞宿主页面。
   */
  function cssVars() {
    const L = []
    Object.keys(color).forEach(function (k) { L.push('--lz-c-' + k + ':' + color[k]) })
    Object.keys(radius).forEach(function (k) { L.push('--lz-r-' + k + ':' + radius[k]) })
    Object.keys(space).forEach(function (k) { L.push('--lz-s-' + k + ':' + space[k]) })
    Object.keys(font).forEach(function (k) { L.push('--lz-f-' + k + ':' + font[k]) })
    Object.keys(shadow).forEach(function (k) { L.push('--lz-sh-' + k + ':' + shadow[k]) })
    Object.keys(z).forEach(function (k) { L.push('--lz-z-' + k + ':' + z[k]) })
    Object.keys(motion).forEach(function (k) { L.push('--lz-m-' + k + ':' + motion[k]) })
    return L.join(';')
  }

  /** 注入变量（幂等）。任何用到 --lz-* 的地方调用前先确保它跑过。 */
  function ensure() {
    if (document.getElementById('liaison-ui-tokens')) return
    const st = document.createElement('style')
    st.id = 'liaison-ui-tokens'
    st.textContent = ':root{' + cssVars() + '}'
    ;(document.head || document.documentElement).appendChild(st)
  }

  window.__liaisonUITokens = {
    color: color, radius: radius, space: space,
    font: font, shadow: shadow, z: z, motion: motion,
    cssVars: cssVars, ensure: ensure,
  }
})()
